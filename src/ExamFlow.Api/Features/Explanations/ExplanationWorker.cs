namespace ExamFlow.Api.Features.Explanations;

/// <summary>Wakes the worker when an admin starts a run (it also polls, so a missed signal only delays).</summary>
public sealed class ExplanationQueue
{
    private readonly SemaphoreSlim _signal = new(0, 1);

    public void Notify()
    {
        if (_signal.CurrentCount == 0) try { _signal.Release(); } catch (SemaphoreFullException) { }
    }

    public Task WaitAsync(TimeSpan timeout, CancellationToken ct) => _signal.WaitAsync(timeout, ct);
}

/// <summary>Database side of generation: which questions still need an explanation, and the month's spend.</summary>
public sealed class ExplanationService(AppDbContext db, TimeProvider clock)
{
    /// <summary>
    /// Questions of a PDF that can be explained (multiple choice, known key) and have no explanation of their content
    /// in the bank yet, in PDF order. Any existing row (Draft, Review, Approved or Rejected) counts, so nothing is
    /// regenerated by accident; identical questions inside the PDF are sent once.
    /// </summary>
    public async Task<List<ExplanationCandidate>> PendingAsync(Guid documentId, IReadOnlyCollection<Guid> skip, CancellationToken ct)
    {
        var questions = await db.Questions.AsNoTracking()
            .Where(q => q.DocumentId == documentId && q.VerificationStatus != VerificationStatus.Unverified
                && q.Options.Count >= 2 && q.Options.Count(o => o.IsCorrect) == 1)
            .OrderBy(q => q.SourceNumber)
            .Select(q => new { q.Id, q.Text, Options = q.Options.OrderBy(o => o.Position).Select(o => new { o.Position, o.Label, o.Text, o.IsCorrect }).ToList() })
            .ToListAsync(ct);
        var visuals = (await db.QuestionVisuals.AsNoTracking()
            .Where(v => v.DocumentId == documentId && v.QuestionId != null && v.MappingStatus != QuestionVisualStatus.Ignored
                && v.StorageKey != null && v.ContentType != null)
            .OrderBy(v => v.SortOrder)
            .Select(v => new { QuestionId = v.QuestionId!.Value, v.OptionPosition, StorageKey = v.StorageKey!, ContentType = v.ContentType! })
            .ToListAsync(ct)).ToLookup(v => v.QuestionId);

        var candidates = questions
            .Where(q => !skip.Contains(q.Id))
            .Select(q =>
            {
                var correct = q.Options.First(o => o.IsCorrect);
                var options = q.Options.Select(o => new ExplanationOption(o.Label, o.Text)).ToList();
                var images = visuals[q.Id].Select(v => new ExplanationImage(
                    v.OptionPosition is { } p ? q.Options.FirstOrDefault(o => o.Position == p)?.Label : null, v.StorageKey, v.ContentType)).ToList();
                // Image questions go to the math model: they usually need visual reasoning, and its image tokens are cheaper.
                var type = images.Count > 0 || ExplanationEngine.IsMath(q.Text, options.Select(o => o.Text).ToList())
                    ? ExplanationQuestionType.Math : ExplanationQuestionType.Theory;
                return new ExplanationCandidate(q.Id, ExplanationEngine.Fingerprint(q.Text, options.Select(o => o.Text), correct.Text)!, q.Text, options,
                    correct.Label, type, images);
            })
            .DistinctBy(c => Convert.ToHexString(c.Fingerprint))
            .ToList();
        if (candidates.Count == 0) return candidates;

        var keys = candidates.Select(c => c.Fingerprint).ToList();
        var existing = (await db.QuestionExplanations.AsNoTracking().Where(e => keys.Contains(e.Fingerprint)).Select(e => e.Fingerprint).ToListAsync(ct))
            .Select(Convert.ToHexString).ToHashSet();
        return candidates.Where(c => !existing.Contains(Convert.ToHexString(c.Fingerprint))).ToList();
    }

    /// <summary>Spend of all runs started this calendar month (UTC), failed calls included.</summary>
    public async Task<decimal> MonthSpentAsync(CancellationToken ct)
    {
        var now = clock.GetUtcNow();
        var monthStart = new DateTimeOffset(now.Year, now.Month, 1, 0, 0, 0, TimeSpan.Zero);
        return await db.ExplanationJobs.AsNoTracking().Where(j => j.CreatedAt >= monthStart).SumAsync(j => (decimal?)j.SpentUsd, ct) ?? 0m;
    }
}

/// <summary>
/// Runs explanation jobs one batch at a time. Every batch is saved before the next request, so a restart (Render deploy,
/// crash) loses at most the request in flight; unfinished runs are picked up again on start. A session-owned app lock
/// keeps a second API instance from working (and paying) in parallel; it is released when the connection drops.
/// </summary>
public sealed class ExplanationWorker(IServiceScopeFactory scopes, ExplanationQueue queue, IOptionsMonitor<ExplanationAiOptions> options,
    TimeProvider clock, ILogger<ExplanationWorker> logger) : BackgroundService
{
    private static readonly TimeSpan Poll = TimeSpan.FromSeconds(30);

    protected override async Task ExecuteAsync(CancellationToken stoppingToken)
    {
        while (!stoppingToken.IsCancellationRequested)
        {
            try
            {
                if (options.CurrentValue.Enabled) await RunPendingAsync(stoppingToken);
            }
            catch (OperationCanceledException) when (stoppingToken.IsCancellationRequested) { return; }
            catch (Exception ex)
            {
                logger.LogError(ex, "Explanation worker loop failed");
            }

            try { await queue.WaitAsync(Poll, stoppingToken); }
            catch (OperationCanceledException) { return; }
        }
    }

    private async Task RunPendingAsync(CancellationToken ct)
    {
        using var scope = scopes.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
        if (!await db.ExplanationJobs.AnyAsync(j => j.Status == ExplanationJobStatus.Pending || j.Status == ExplanationJobStatus.Running, ct)) return;

        await db.Database.OpenConnectionAsync(ct);
        try
        {
            if (!await TryLockAsync(db, ct)) return; // another instance is working
            while (!ct.IsCancellationRequested && options.CurrentValue.Enabled)
            {
                var jobId = await db.ExplanationJobs.AsNoTracking()
                    .Where(j => j.Status == ExplanationJobStatus.Pending || j.Status == ExplanationJobStatus.Running)
                    .OrderBy(j => j.CreatedAt).Select(j => (Guid?)j.Id).FirstOrDefaultAsync(ct);
                if (jobId is null) return;
                using var jobScope = scopes.CreateScope();
                await ProcessAsync(jobScope.ServiceProvider, jobId.Value, ct);
            }
        }
        finally { await db.Database.CloseConnectionAsync(); }
    }

    private static async Task<bool> TryLockAsync(AppDbContext db, CancellationToken ct)
    {
        await using var command = db.Database.GetDbConnection().CreateCommand();
        command.CommandText = "DECLARE @r int; EXEC @r = sp_getapplock @Resource = 'explanation-worker', @LockMode = 'Exclusive', @LockOwner = 'Session', @LockTimeout = 0; SELECT @r;";
        return Convert.ToInt32(await command.ExecuteScalarAsync(ct)) >= 0;
    }

    private async Task ProcessAsync(IServiceProvider services, Guid jobId, CancellationToken ct)
    {
        var db = services.GetRequiredService<AppDbContext>();
        var bank = services.GetRequiredService<ExplanationService>();
        var generator = services.GetRequiredService<ExplanationGenerator>();
        var job = await db.ExplanationJobs.FirstAsync(j => j.Id == jobId, ct);
        if (job.Status == ExplanationJobStatus.Pending)
        {
            job.Status = ExplanationJobStatus.Running;
            await db.SaveChangesAsync(ct);
        }

        var failuresInRow = 0;
        while (!ct.IsCancellationRequested)
        {
            var o = options.CurrentValue;
            await db.Entry(job).ReloadAsync(ct); // an admin may have cancelled it
            if (job.Status != ExplanationJobStatus.Running) return;
            if (!o.Enabled) return; // switched off: stays Running and resumes when switched on again

            var left = job.Total - job.Done - job.Failed;
            var pending = left <= 0 ? [] : await bank.PendingAsync(job.DocumentId, job.FailedQuestionIds, ct);
            if (pending.Count == 0)
            {
                await FinishAsync(db, job, ExplanationJobStatus.Completed, null, ct);
                return;
            }

            var batch = ExplanationEngine.Batches(pending.Take(left), o).First();
            if (await bank.MonthSpentAsync(ct) + ExplanationEngine.WorstCaseCost(batch, o) > o.MonthlyBudgetUsd)
            {
                await FinishAsync(db, job, ExplanationJobStatus.BudgetExhausted, "budget", ct);
                return;
            }

            (ChatModelUsage Usage, decimal Cost)? paid = null;
            try
            {
                var (json, usage, model) = await generator.GenerateAsync(batch, ct);
                failuresInRow = 0;
                // Mock runs are charged at the configured prices too, so the budget path is exercised before real use.
                var cost = Math.Round(o.CostOf(batch[0].Type, usage.InputTokens, usage.OutputTokens), 6);
                paid = (usage, cost);
                Charge(job, usage, cost);
                Store(db, job, batch, ExplanationEngine.Parse(json, batch, ExplanationConfiguration.MaxExplanationLength), model, usage, cost);
                await db.SaveChangesAsync(ct);
                logger.LogInformation("Explanation job {Job}: {Count} questions via {Model}, {Input} in / {Output} out tokens, {Cost} USD",
                    job.Id, batch.Count, model, usage.InputTokens, usage.OutputTokens, cost);
            }
            catch (ChatModelException ex)
            {
                if (ex.Usage is { } billed) Charge(job, billed, o.CostOf(batch[0].Type, billed.InputTokens, billed.OutputTokens));
                logger.LogWarning("Explanation job {Job}: model call failed ({Failure})", job.Id, ex.Failure);
                switch (ex.Failure)
                {
                    case ChatModelFailure.InvalidOutput:
                        // Paid but unusable: these questions are not retried in this run.
                        job.FailedQuestionIds.AddRange(batch.Select(c => c.QuestionId));
                        job.Failed += batch.Count;
                        job.LastError = "invalid-output";
                        await db.SaveChangesAsync(ct);
                        break;
                    case ChatModelFailure.RateLimited or ChatModelFailure.Unavailable or ChatModelFailure.Timeout when ++failuresInRow < o.MaxConsecutiveFailures:
                        job.LastError = ex.Failure.ToString().ToLowerInvariant();
                        await db.SaveChangesAsync(ct);
                        await Task.Delay(TimeSpan.FromSeconds(5 * failuresInRow), ct);
                        break;
                    default:
                        await FinishAsync(db, job, ExplanationJobStatus.Failed, ex.Failure.ToString().ToLowerInvariant(), ct);
                        return;
                }
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                // Anything else (e.g. saving failed after a paid call) stops the run instead of looping and paying again.
                logger.LogError(ex, "Explanation job {Job} stopped after an unexpected error", job.Id);
                db.ChangeTracker.Clear();
                job = await db.ExplanationJobs.FirstAsync(j => j.Id == jobId, ct);
                if (paid is { } p) Charge(job, p.Usage, p.Cost);
                await FinishAsync(db, job, ExplanationJobStatus.Failed, "unexpected", ct);
                return;
            }
        }
    }

    private static void Charge(ExplanationJob job, ChatModelUsage usage, decimal cost)
    {
        job.Requests++;
        job.InputTokens += usage.InputTokens;
        job.OutputTokens += usage.OutputTokens;
        job.SpentUsd += cost;
    }

    private static void Store(AppDbContext db, ExplanationJob job, IReadOnlyList<ExplanationCandidate> batch, IReadOnlyList<ExplanationItemResult> results,
        string model, ChatModelUsage usage, decimal cost)
    {
        // The request's tokens and cost are split evenly over its questions (the API reports them per request only).
        var share = batch.Count;
        foreach (var (candidate, result) in batch.Zip(results))
        {
            if (!result.Ok)
            {
                job.FailedQuestionIds.Add(candidate.QuestionId);
                job.Failed++;
                continue;
            }
            db.QuestionExplanations.Add(new QuestionExplanation
            {
                Id = Guid.NewGuid(),
                Fingerprint = candidate.Fingerprint,
                SourceQuestionId = candidate.QuestionId,
                Explanation = result.Explanation!,
                QuestionType = result.Type,
                Status = result.Status,
                ReviewReason = result.ReviewReason,
                Model = model,
                InputTokens = usage.InputTokens / share,
                OutputTokens = usage.OutputTokens / share,
                CostUsd = Math.Round(cost / share, 6),
            });
            job.Done++;
        }
        if (results.Any(r => !r.Ok)) job.LastError = "invalid-item";
    }

    private async Task FinishAsync(AppDbContext db, ExplanationJob job, ExplanationJobStatus status, string? error, CancellationToken ct)
    {
        job.Status = status;
        job.LastError = error ?? job.LastError;
        job.CompletedAt = clock.GetUtcNow();
        await db.SaveChangesAsync(ct);
        logger.LogInformation("Explanation job {Job} finished: {Status}, {Done} done, {Failed} failed, {Spent} USD", job.Id, status, job.Done, job.Failed, job.SpentUsd);
    }
}
